"""Regenerate Kotlin interface copy from the editable English JSON catalog."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
copy=json.loads((root/'app/src/main/assets/i18n/en.json').read_text(encoding='utf-8'))
for key,value in copy.items():
 assert set(re.findall(r'\{\d+\}',key))==set(re.findall(r'\{\d+\}',value)),key
missing=set()
for path in (root/'app/src/main/kotlin').rglob('*.kt'):
 if path.name=='EnglishCatalog.kt':continue
 for raw in re.findall(r'\btr\("((?:[^"\\]|\\.)*)"',path.read_text(encoding='utf-8')):
  key=json.loads('"'+raw+'"')
  if key not in copy:missing.add(key)
assert not missing,missing
quote=lambda s:json.dumps(s,ensure_ascii=False).replace('$','\\$')
text='package com.agenda.app.design\n\n// Generated by tools/generate_ui_catalog.py from assets/i18n/en.json.\ninternal val EnglishCopy=mapOf(\n'+',\n'.join('    '+quote(k)+' to '+quote(v) for k,v in copy.items())+'\n)\n'
(root/'app/src/main/kotlin/com/agenda/app/design/EnglishCatalog.kt').write_text(text,encoding='utf-8')
print(f'Generated {len(copy)} entries; all literal UI calls covered, argument placeholders preserved.')
